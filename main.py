def _normalise_token(value):
    return re.sub(r"[^a-z0-9]+", "", str(value).lower())


def _case_dir_score(directory, case):
    name = _normalise_token(directory.name)
    key = _normalise_token(case["key"])
    storm = _normalise_token(case["storm"])
    time_digits = _normalise_token(case["time"].replace("UTC", ""))
    score = 0
    if key and key in name:
        score += 100
    if time_digits and time_digits in name:
        score += 80
    if storm and storm in name:
        score += 30
    return score


def _build_replay_frame_map():
    """Discover the supplied replay bundle regardless of whether it stores original filenames or frame_t*.jpg."""
    global _REPLAY_FRAME_MAP
    frame_map = {}

    if not BUNDLE_ROOT.exists():
        _REPLAY_FRAME_MAP = {}
        return frame_map

    all_jpgs = []
    try:
        all_jpgs = [p for p in BUNDLE_ROOT.rglob("*.jpg") if p.is_file()]
    except Exception:
        all_jpgs = []

    # 1. Exact original filenames.
    by_name = {}
    for path in all_jpgs:
        by_name.setdefault(path.name.lower(), path)
    for case in REPLAY_CASES:
        exact = [by_name.get(name.lower()) for name in case["frame_files"]]
        if all(exact):
            frame_map[case["key"]] = exact

    # 2. Manifest-driven paths, when present.
    manifest_path = BUNDLE_ROOT / "manifest.csv"
    if manifest_path.exists():
        try:
            with manifest_path.open("r", encoding="utf-8", newline="") as handle:
                for row in csv.DictReader(handle):
                    raw_case = row.get("case") or row.get("key") or ""
                    matched = next((c for c in REPLAY_CASES if raw_case == c["key"]), None)
                    if matched is None:
                        storm = _normalise_token(row.get("storm", ""))
                        time_digits = _normalise_token(row.get("time", ""))
                        candidates = [
                            c for c in REPLAY_CASES
                            if _normalise_token(c["storm"]) == storm
                            and (not time_digits or time_digits in _normalise_token(c["time"]))
                        ]
                        if len(candidates) == 1:
                            matched = candidates[0]
                    if matched is None:
                        continue
                    jpg_values = []
                    for key, value in row.items():
                        if "frame" not in key.lower() or not value:
                            continue
                        parts = [x.strip() for x in str(value).split(";") if x.strip()]
                        for part in parts:
                            if part.lower().endswith(".jpg"):
                                candidate = BUNDLE_ROOT / part
                                if not candidate.exists():
                                    candidate = by_name.get(Path(part).name.lower())
                                if candidate and candidate.exists():
                                    jpg_values.append(candidate)
                    if len(jpg_values) >= 4:
                        frame_map[matched["key"]] = jpg_values[:4]
        except Exception:
            pass

    # 3. Case-directory fallback. This matches bundles containing case folders with frame_t0..frame_t3.jpg.
    directories = [p for p in BUNDLE_ROOT.iterdir() if p.is_dir()]
    for case in REPLAY_CASES:
        if case["key"] in frame_map:
            continue
        scored = []
        for directory in directories:
            jpgs = sorted(p for p in directory.glob("*.jpg") if p.is_file())
            if len(jpgs) >= 4:
                score = _case_dir_score(directory, case)
                if score > 0:
                    scored.append((score, directory, jpgs))
        if scored:
            scored.sort(key=lambda x: (-x[0], x[1].name.lower()))
            frame_map[case["key"]] = scored[0][2][:4]

    # 4. If the bundle is exactly four case directories, use their deterministic order only for cases still unmatched.
    if len(frame_map) < len(REPLAY_CASES):
        candidates = []
        for directory in directories:
            jpgs = sorted(p for p in directory.glob("*.jpg") if p.is_file())
            if len(jpgs) >= 4:
                candidates.append((directory.name.lower(), jpgs[:4]))
        candidates.sort(key=lambda x: x[0])
        unused = [c for c in REPLAY_CASES if c["key"] not in frame_map]
        if len(candidates) == len(REPLAY_CASES):
            for case, (_, jpgs) in zip(unused, candidates):
                frame_map[case["key"]] = jpgs

    _REPLAY_FRAME_MAP = frame_map
    return frame_map


def _replay_bundle_complete():
    frame_map = _REPLAY_FRAME_MAP or _build_replay_frame_map()
    return all(
        case["key"] in frame_map and len(frame_map[case["key"]]) >= 4
        for case in REPLAY_CASES
    )


def ensure_replay_assets():
    """Prepare the supplied demo bundle locally. No live archive download is attempted."""
    if _replay_bundle_complete():
        _write_replay_metadata()
        return "local v4_demo_bundle"

    for archive in _local_replay_archives():
        try:
            if _extract_from_local_archive(archive) and _replay_bundle_complete():
                return f"local archive • {archive.name}"
        except Exception:
            continue

    raise FileNotFoundError(
        "The supplied v4_demo_bundle could not be located. "
        "Place the existing v4_demo_bundle folder next to main.py. "
        "The app does not download the 5 GB+ source archive during a demo."
    )


def resolve_bundle_frame(filename):
    """Resolve an original dataset filename from the local demo bundle or its case mapping."""
    direct = BUNDLE_ROOT / filename
    if direct.exists():
        return direct

    frame_map = _REPLAY_FRAME_MAP or _build_replay_frame_map()
    for files in frame_map.values():
        for path in files:
            if path.name.lower() == Path(filename).name.lower():
                return path

    try:
        for path in BUNDLE_ROOT.rglob(filename):
            if path.is_file():
                return path
    except Exception:
        pass
    return None


def case_frames(case):
    frame_map = _REPLAY_FRAME_MAP or _build_replay_frame_map()
    mapped = frame_map.get(case["key"], [])
    if len(mapped) >= 4:
        return mapped[:4]
    return [resolve_bundle_frame(x) for x in case["frame_files"]]




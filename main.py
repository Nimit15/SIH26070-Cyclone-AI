def _safe_archive_members(archive):
    """Yield JPG members from a local demo archive without path traversal."""
    for info in archive.infolist():
        if info.is_dir() or not info.filename.lower().endswith(".jpg"):
            continue
        parts = [part for part in Path(info.filename).parts if part not in ("", ".", "..")]
        if parts:
            yield info, Path(*parts)



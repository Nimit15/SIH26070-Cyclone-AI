def predict_dashboard(image):
    tensor = transform(image).unsqueeze(0).to(DEVICE)
    with torch.no_grad():
        logits, wind = model(tensor)
        probs = torch.softmax(logits, dim=1)[0]
        order = torch.argsort(probs, descending=True)
        idx = int(order[0].item())
        category = CATEGORIES[idx]
        confidence = float(probs[idx].item())
        second = CATEGORIES[int(order[1].item())]
        second_score = float(probs[int(order[1].item())].item())
        predicted_wind = float(wind.item())

    cam = generate_focus_map(tensor, idx)
    focus = create_focus_map_image(image, cam)
    return {
        "category": category,
        "category_name": class_name(category, "en"),
        "wind": predicted_wind,
        "confidence": confidence,
        "second": second,
        "second_score": second_score,
        "focus": focus,
    }



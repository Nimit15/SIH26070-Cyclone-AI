def regional_satellite_url(area):
    area = area if area in AREA_FOCUS else "All India"
    lat, lon, span = AREA_FOCUS[area]
    if area == "All India":
        bbox = "5,68,25,95"
    else:
        bbox = f"{max(-90, lat-span):.2f},{max(-180, lon-span):.2f},{min(90, lat+span):.2f},{min(180, lon+span):.2f}"
    day = datetime.utcnow().strftime("%Y-%m-%d")
    return (
        "https://gibs.earthdata.nasa.gov/wms/epsg4326/best/wms.cgi"
        "?SERVICE=WMS&VERSION=1.3.0&REQUEST=GetMap"
        "&LAYERS=VIIRS_SNPP_CorrectedReflectance_TrueColor"
        "&CRS=EPSG:4326"
        f"&BBOX={bbox}"
        "&WIDTH=900&HEIGHT=700&FORMAT=image/jpeg"
        f"&TIME={day}"
    )



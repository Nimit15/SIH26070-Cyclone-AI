transform = transforms.Compose([
    transforms.Resize((224, 224)),
    transforms.ToTensor(),
    transforms.Normalize(
        mean=[0.485, 0.456, 0.406],
        std=[0.229, 0.224, 0.225],
    ),
])


def image_to_data_url(image):
    buffer = BytesIO()
    image.save(buffer, format="PNG")
    encoded = base64.b64encode(buffer.getvalue()).decode()
    return "data:image/png;base64," + encoded


def generate_focus_map(image_tensor, class_index):
    activations = []
    gradients = []
    target_layer = model.backbone.conv_head

    def forward_hook(_, __, output):
        activations.append(output)

    def backward_hook(_, __, grad_output):
        gradients.append(grad_output[0])

    forward_handle = target_layer.register_forward_hook(forward_hook)
    backward_handle = target_layer.register_full_backward_hook(backward_hook)

    try:
        model.zero_grad()
        logits, _ = model(image_tensor)
        logits[0, class_index].backward()

        activation = activations[0].detach()
        gradient = gradients[0].detach()
    finally:
        forward_handle.remove()
        backward_handle.remove()

    weights = gradient.mean(dim=(2, 3), keepdim=True)
    cam = (weights * activation).sum(dim=1, keepdim=True)
    cam = torch.relu(cam)

    cam = torch.nn.functional.interpolate(
        cam,
        size=(224, 224),
        mode="bilinear",
        align_corners=False,
    )

    cam = cam.squeeze().cpu().numpy()
    cam -= cam.min()

    if cam.max() > 0:
        cam /= cam.max()

    return cam


def create_focus_map_image(image, cam):
    import matplotlib

    matplotlib.use("Agg")

    import matplotlib.pyplot as plt

    image = image.resize((224, 224))
    base = np.asarray(image, dtype=np.float32) / 255.0
    heatmap = plt.get_cmap("viridis")(cam)[..., :3]

    blended = 0.55 * base + 0.45 * heatmap
    blended = np.clip(blended * 255, 0, 255).astype(np.uint8)

    return Image.fromarray(blended)


def run_prediction(image: Image.Image):
    tensor = transform(image).unsqueeze(0).to(DEVICE)

    with torch.no_grad():
        logits, wind = model(tensor)
        probabilities = torch.softmax(logits, dim=1)[0]

        class_index = torch.argmax(probabilities).item()
        classifier_category = CATEGORIES[class_index]
        confidence = probabilities[class_index].item()
        predicted_wind = wind.item()

    if predicted_wind >= SUCS_THRESHOLD:
        final_category = "SuCS"
        reason = (
            f"The estimated wind speed ({predicted_wind:.1f} kt) is very high, "
            "so this is marked as the most serious level."
        )
    else:
        final_category = classifier_category
        reason = "This level is based on the overall cloud pattern the AI recognized."

    cam = generate_focus_map(tensor, class_index)
    focus_img = create_focus_map_image(image, cam)

    return (
        final_category,
        predicted_wind,
        confidence,
        reason,
        focus_img,
    )



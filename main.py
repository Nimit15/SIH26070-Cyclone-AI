def build_gibs_url(date_str: str) -> str:
    bbox = "5,68,25,95"

    return (
        "https://gibs.earthdata.nasa.gov/wms/epsg4326/best/wms.cgi"
        "?SERVICE=WMS&VERSION=1.3.0&REQUEST=GetMap"
        "&LAYERS=VIIRS_SNPP_CorrectedReflectance_TrueColor"
        "&CRS=EPSG:4326"
        f"&BBOX={bbox}"
        "&WIDTH=800&HEIGHT=800"
        "&FORMAT=image/jpeg"
        f"&TIME={date_str}"
    )


def get_timelapse_images(num_days: int = 5):
    frames = []

    for days_back in range(num_days, -1, -1):
        date_str = (
            datetime.utcnow() - timedelta(days=days_back)
        ).strftime("%Y-%m-%d")

        url = build_gibs_url(date_str)

        try:
            response = requests.get(url, timeout=15)

            if response.status_code == 200 and len(response.content) > 5000:
                frames.append((date_str, response.content))

        except Exception:
            continue

    if not frames:
        raise ValueError("No recent satellite images available")

    return frames



def wind_to_category(wind):
    """Map a wind estimate to the project's six-class training taxonomy."""
    value = float(wind)
    if value <= 27.5:
        return "D"
    if value <= 32.5:
        return "DD"
    if value <= 47.5:
        return "CS"
    if value <= 62.5:
        return "SCS"
    if value <= 117.5:
        return "VSCS"
    return "SuCS"


